#!/usr/bin/env bash
#
# Generate the per-image linter tables in LINTERS.md from the Dockerfiles.
#
# There is one image variant per images/<variant>/Dockerfile, and one table region per variant in
# LINTERS.md, marked by <!-- linters:<variant>:start --> / <!-- linters:<variant>:end --> and filled
# from that variant's Dockerfile. The Dockerfiles are the single source of truth.
#
# For each Lane-1 tool the version and upstream image come from its `FROM <img>:<tag>@<digest> AS
# <name>` line. What it lints and its repo link come from a `# linter:` annotation directly above
# that FROM:
#
#     # linter: lints: Dockerfiles | repo: https://github.com/hadolint/hadolint
#     FROM hadolint/hadolint:v2.14.0-alpine@sha256:... AS hadolint
#
# A Lane-2 tool has no FROM, so its annotation also names the tool, and sits directly above the
# `ARG <NAME>_VERSION=` that pins its version (the one source Renovate bumps):
#
#     # linter: tool: ktlint | lints: Kotlin | repo: https://github.com/ktlint/ktlint
#     # renovate: datasource=github-releases depName=ktlint/ktlint
#     ARG KTLINT_VERSION=1.8.0
#
# Only comments may sit between an annotation and its line. Anything else is an error, so a tool
# can't drop out of the table unnoticed.
#
# The tables are written between the markers in LINTERS.md, and the rest of that file is hand-written
# and left untouched.
#
# Usage:
#   ./scripts/gen-linters.sh           rewrite every table in LINTERS.md
#   ./scripts/gen-linters.sh --check   exit non-zero if LINTERS.md is stale (writes nothing)
#
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.." || exit 1

manifest='LINTERS.md'

tmp_table=''
tmp_out=''
cleanup() {
  if [ -n "${tmp_table:-}" ]; then rm -f "$tmp_table"; fi
  if [ -n "${tmp_out:-}" ]; then rm -f "$tmp_out" "${tmp_out}.new"; fi
}
trap cleanup EXIT

# Image variants: one per images/<variant>/Dockerfile.
list_variants() {
  for d in images/*/; do
    [ -f "${d}Dockerfile" ] && basename "$d"
  done
}

# Emit the markdown table (header + one row per tool) for the Dockerfile in $1, to stdout.
gen_table() {
  awk -v src="$1" '
    function trim(s) { gsub(/^[ \t]+|[ \t]+$/, "", s); return s }
    function field(key,   n, parts, i, p) {
      n = split(ann, parts, "|")
      for (i = 1; i <= n; i++) {
        p = index(parts[i], ":")
        if (p > 0 && trim(substr(parts[i], 1, p - 1)) == key) return trim(substr(parts[i], p + 1))
      }
      return ""
    }
    function row(name, ver, img) {
      printf "| [%s](%s) | %s | %s | %s | %s |\n", name, field("repo"), ver,
        (lane == 1 ? "1 (static)" : "2"), field("lints"), img
      lane = 0
    }
    function report(   want) {
      want = (lane == 1) ? "FROM <image>:<tag>@<digest> AS <name>" : "ARG <NAME>_VERSION=<version>"
      printf "%s:%d: a `# linter:` annotation must be followed by %s\n", src, at, want > "/dev/stderr"
      failed = 1
    }
    BEGIN {
      print "<!-- Autogenerated by scripts/gen-linters.sh from " src ". Do not edit by hand. -->"
      print "| Tool | Version | Lane | Lints | Upstream image |"
      print "| --- | --- | --- | --- | --- |"
    }
    /^[[:space:]]*#[[:space:]]*linter:/ {
      if (lane) { report(); exit }
      ann = $0
      sub(/^[[:space:]]*#[[:space:]]*linter:[[:space:]]*/, "", ann)
      at = FNR
      lane = (field("tool") == "") ? 1 : 2
      next
    }
    !lane || /^[[:space:]]*(#|$)/ { next }
    lane == 1 && toupper($1) == "FROM" && NF == 4 && toupper($3) == "AS" {
      img = $2; sub(/@.*/, "", img)
      tag = img
      if (!sub(/.*:/, "", tag)) { report(); exit }
      row($4, tag, "`" img "`")
      next
    }
    lane == 2 && toupper($1) == "ARG" && NF == 2 && $2 ~ /^[A-Za-z0-9_]+_VERSION=./ {
      ver = $2; sub(/^[^=]*=/, "", ver); gsub(/^"|"$/, "", ver)
      row(field("tool"), ver, "n/a")
      next
    }
    { report(); exit }
    END {
      if (lane && !failed) report()
      if (failed) exit 2
    }
  ' "$1"
}

# Print $1 with the region between markers $3 / $4 replaced by the contents of file $2.
replace_section() {
  awk -v tablefile="$2" -v s="$3" -v e="$4" '
    BEGIN { while ((getline line < tablefile) > 0) tbl = tbl line "\n"; sub(/\n$/, "", tbl) }
    index($0, s) { print; print tbl; skip = 1; next }
    index($0, e) { skip = 0; print; next }
    skip { next }
    { print }
  ' "$1"
}

main() {
  variant_list=()
  while IFS= read -r v; do
    if [ -n "$v" ]; then variant_list+=("$v"); fi
  done < <(list_variants)

  if [ "${#variant_list[@]}" -eq 0 ]; then
    echo "error: no image variants found (images/*/Dockerfile)" >&2
    exit 2
  fi

  tmp_table="$(mktemp)"
  tmp_out="$(mktemp)"
  cp "$manifest" "$tmp_out"

  for v in "${variant_list[@]}"; do
    start="<!-- linters:${v}:start -->"
    end="<!-- linters:${v}:end -->"
    if ! grep -qF "$start" "$tmp_out" || ! grep -qF "$end" "$tmp_out"; then
      printf 'error: %s is missing the "%s" / "%s" markers for variant %s\n' "$manifest" "$start" "$end" "$v" >&2
      exit 2
    fi
    gen_table "images/${v}/Dockerfile" >"$tmp_table"
    replace_section "$tmp_out" "$tmp_table" "$start" "$end" >"${tmp_out}.new"
    mv "${tmp_out}.new" "$tmp_out"
  done

  if [ "${1:-}" = '--check' ]; then
    if diff -u "$manifest" "$tmp_out" >/dev/null; then
      echo "LINTERS.md is up to date"
    else
      echo "LINTERS.md is stale; run ./scripts/gen-linters.sh" >&2
      diff -u "$manifest" "$tmp_out" >&2 || true
      exit 1
    fi
  else
    cat "$tmp_out" >"$manifest"
    echo "updated $manifest"
  fi
}

main "$@"
